
class AnalysisResult{
    int min;
    int max;
    double median;

    int getMin(){
        return this.min;
    }
    void setMin(int min){
        this.min = min;
    }
    int getMax(){
        return this.max; 
    }
    void setMax(int max){
        this.max = max;
    }
    double getMedian(){
        return this.median;
    }
    void setMedian(double median){
        this.median = median;
    }
}